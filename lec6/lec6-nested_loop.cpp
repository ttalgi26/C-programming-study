/*

 [개념 정리 - 중첩 반복문(nested loop)]
 - 반복문 안에 다른 반복문이 들어있는 것
 - 바깥 반복 1번 돌 때 안쪽 반복은 처음부터 끝까지 전부 돎
     총 실행 횟수 = 바깥 횟수 x 안쪽 횟수 (5 x 10 = 50개의 *)
 - 바깥 반복 = 행(줄), 안쪽 반복 = 열(칸)
 - 안쪽과 바깥쪽의 반복 제어 변수는 서로 달라야 함 (x, y)

*/

#include <stdio.h>

int main(void) {
	int x, y;

	for (y = 0; y < 5; y++)	// 바깥 반복문 : 5줄
	{
		for (x = 0; x < 10; x++)	// 안쪽 반복문 : 한 줄에 10개
			printf("*");
		printf("\n");	// 안쪽 반복문이 끝날 때마다 줄바꿈
	}

	return 0;
}
