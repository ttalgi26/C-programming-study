/*

 [개념 정리 - 변수, 대입 연산, 산술 연산]
 - 변수(variable) : 프로그램이 사용하는 데이터를 일시적으로 저장하는 메모리 공간
 - 변수 선언 : 자료형 변수이름;  -> 컴파일러에게 어떤 타입의 변수를 쓸지 미리 알림
 - 자료형(data type) : 변수가 저장할 데이터의 종류 (int 정수, double 실수, char 문자 ...)
 - 대입(할당) 연산 = : 오른쪽 값을 왼쪽 변수에 저장 (수학의 "같다"가 아님!)
 - 일반적인 프로그램 흐름 : 입력 -> 처리 -> 출력
 - printf("%d", sum) : %d 자리에 sum의 값을 10진 정수로 출력 (형식 지정자)

*/

#include <stdio.h>

int main(void)
{
  int x;	// 첫 번째 정수를 저장할 변수
  int y;	// 두 번째 정수를 저장할 변수
  int sum;	// 두 정수의 합을 저장할 변수
  x = 100;	// 대입 연산
  y = 200;
  sum = x + y;	// 산술 연산 후 결과를 sum에 대입
  printf("sum = %d\n", sum);
  return 0;
}
