/*
프로그래밍 기초 - 2주차 수업
(대충 이렇게 주석달면 크게 할 수 있다는 내용)

 [개념 정리 - C 프로그램의 구성요소]
 - #include <stdio.h> : 헤더 파일 포함. printf()/scanf() 같은 표준 입출력 함수 정보를 가져옴
 - main() : C 프로그램에서 "가장 먼저" 실행되는 함수 (프로그램의 시작점)
 - 함수 = 특정한 작업을 수행하는 코드의 집합 (입력 -> 블랙박스 -> 출력)
 - 함수 구성 : 반환형(int) + 함수 이름(main) + (매개변수) + { 함수 몸체 }
 - 문장은 반드시 ;(세미콜론)으로 끝나야 함, 위에서 아래로 "순차적"으로 실행
 - return 0; : 함수를 종료하고 0을 외부(운영체제)로 반환
 - 주석 2가지 : 여러 줄 주석 / * ... * / , 한 줄 주석 //  (컴파일러가 무시함)
 - \n : 줄바꿈 문자 (커서를 다음 줄 맨 앞으로 이동)

 [오류의 종류] (시험 단골)
 - 심각성에 따라 : 에러(error, 컴파일/링크 불가) vs 경고(warning, 실행은 되지만 잠재적 문제)
 - 발생 시점에 따라 :
     컴파일 시간 오류 - 대부분 문법 오류 (예: 세미콜론 빠짐)
     실행 시간 오류   - 실행 도중 발생 (예: 0으로 나누기)
     논리 오류        - 실행은 되지만 결과가 의도와 다름

*/
//이것도 주석임
#include <stdio.h>	//standard input/output

int main(void)
{
	printf("Hello World!\n");	// \n 없으면 다음 출력이 같은 줄에 붙어서 나옴
	printf("from YeJun\n");
	return 0;
}
