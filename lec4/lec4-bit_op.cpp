/*

 [개념 정리 - 비트 연산자]
 - 비트(bit) : 컴퓨터에서 정보를 저장하는 가장 작은 단위 (0 또는 1)
 - &  비트 AND : 둘 다 1이면 1
 - |  비트 OR  : 하나라도 1이면 1
 - ^  비트 XOR : 서로 다르면 1
 - ~  비트 NOT : 0 <-> 1 반전
 - 논리 연산자(&&, ||, !)와 헷갈리지 말 것! 비트 연산자는 각 비트마다 계산
 - 음수 표현 (2의 보수) : 모든 비트 반전(1의 보수) + 1
     10 = 0000...1010  ->  ~10 = 1111...0101  ->  +1  ->  1111...0110 = -10
     그래서 ~x = -x - 1  (~9 = -10)
 - %08X : 16진수 대문자, 8자리, 빈 자리는 0으로 채움

*/

#include <stdio.h>

int main(void) {
	int x = 9;	// 1001
	int y = 10;	// 1010

	printf("%08X & %08X = %08X\n", x, y, x & y);	// 1000 (8)
	printf("%08X | %08X = %08X\n", x, y, x | y);	// 1011 (B)
	printf("%08X ^ %08X = %08X\n", x, y, x ^ y);	// 0011 (3)
	printf("~ %08X = %08X\n", x, ~x);	// FFFFFFF6 (모든 비트 반전)

	return 0;
}
