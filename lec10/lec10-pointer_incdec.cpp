/*

 ★★★★★ [기말 출제] 간접 참조 연산자와 증감 연산자 ★★★★★
 - 교재에는 표만 있어서 결과를 직접 확인할 수 있게 만든 코드
 - 연습문제 + 정답은 lec10/README.md 의 [기말 출제] 부분 참고

     수식         의미                                          바뀌는 것   순서
     v = *p++    p가 가리키는 값을 v에 대입한 후에 p를 증가          포인터 p    사용 -> 증가
     v = (*p)++  p가 가리키는 값을 v에 대입한 후에 가리키는 값을 증가  값 *p      사용 -> 증가
     v = *++p    p를 증가시킨 후에 p가 가리키는 값을 v에 대입          포인터 p    증가 -> 사용
     v = ++*p    p가 가리키는 값을 증가시킨 후 그 값을 v에 대입        값 *p      증가 -> 사용

 - 구분법 ① 무엇이 증가? -> ++ 가 누구에게 붙었나
     p 에 바로 붙음 (*p++, *++p)       -> 포인터 p 가 다음 칸으로 이동
     *p 덩어리에 붙음 ((*p)++, ++*p)   -> 가리키는 값(배열 원소)이 증가
 - 구분법 ② 언제 증가? -> ++ 위치 (4장 증감 연산자와 같음)
     뒤(후위) : 먼저 사용하고 나중에 증가,   앞(전위) : 먼저 증가하고 사용
 - 함정!! *p++ 은 *(p++) 로 해석됨 (후위 ++ 가 * 보다 먼저 묶임)
     -> 값을 증가시키려면 반드시 괄호 (*p)++
 - *p++ 와 (*p)++ 는 v 값이 똑같이 10 -> 차이는 "p가 움직였나 / 배열 값이 바뀌었나"

*/

#include <stdio.h>

int main(void) {
	int a[] = { 10, 20, 30 };
	int* p;
	int v;

	p = a;	// p는 a[0]을 가리킴
	v = *p++;	// v = 10, 그 다음 p는 a[1]을 가리킴
	printf("v = *p++   : v=%d, *p=%d\n", v, *p);	// v=10, *p=20

	p = a;
	v = (*p)++;	// v = 10, 그 다음 a[0]이 11로 증가
	printf("v = (*p)++ : v=%d, a[0]=%d\n", v, a[0]);	// v=10, a[0]=11

	p = a;
	v = *++p;	// p가 먼저 a[1]로 이동, v = 20
	printf("v = *++p   : v=%d\n", v);	// v=20

	p = a;
	v = ++*p;	// a[0]이 먼저 12로 증가, v = 12
	printf("v = ++*p   : v=%d, a[0]=%d\n", v, a[0]);	// v=12, a[0]=12

	return 0;
}
