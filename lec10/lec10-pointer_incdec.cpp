/*

 [개념 정리 - 간접 참조 연산자와 증감 연산자] (시험 단골!)
 - 교재에는 표만 있어서 결과를 직접 확인할 수 있게 만든 코드
 - *p++   : p가 가리키는 값을 가져온 "후에" p 를 증가 (포인터가 다음 칸으로)
 - (*p)++ : p가 가리키는 "값" 을 증가 (포인터는 그대로)
     v = *p++    p가 가리키는 값을 v에 대입한 후에 p를 증가
     v = (*p)++  p가 가리키는 값을 v에 대입한 후에 가리키는 값을 증가
     v = *++p    p를 증가시킨 후에 p가 가리키는 값을 v에 대입
     v = ++*p    p가 가리키는 값을 증가시킨 후 그 값을 v에 대입
 - 이유 : ++ 와 * 는 우선순위가 같고 결합 방향이 오른쪽 -> 왼쪽
     *p++ 은 *(p++) 로 해석됨

*/

#include <stdio.h>

int main(void) {
	int a[] = { 10, 20, 30 };
	int* p;
	int v;

	p = a;	// p는 a[0]을 가리킴
	v = *p++;	// v = 10, 그 다음 p는 a[1]을 가리킴
	printf("v = *p++   : v=%d, *p=%d\n", v, *p);	// v=10, *p=20

	p = a;
	v = (*p)++;	// v = 10, 그 다음 a[0]이 11로 증가
	printf("v = (*p)++ : v=%d, a[0]=%d\n", v, a[0]);	// v=10, a[0]=11

	p = a;
	v = *++p;	// p가 먼저 a[1]로 이동, v = 20
	printf("v = *++p   : v=%d\n", v);	// v=20

	p = a;
	v = ++*p;	// a[0]이 먼저 12로 증가, v = 12
	printf("v = ++*p   : v=%d, a[0]=%d\n", v, a[0]);	// v=12, a[0]=12

	return 0;
}
