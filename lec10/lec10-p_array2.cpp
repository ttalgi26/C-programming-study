/*

 [개념 정리 - 포인터를 배열처럼, 배열을 포인터처럼] (시험 단골)
 - p = a; 하면 포인터도 배열 이름처럼 사용 가능
     p[i] == a[i]
 - 배열 이름에도 포인터 연산 사용 가능
     *(a + i) == a[i]       (a + i 는 i 번째 요소의 주소)
     *(p + i) == p[i]
 - 차이점 : 포인터 p 는 변수라서 p++ 가능, 배열 이름 a 는 상수라서 a++ 불가능

*/

#include <stdio.h>

int main(void) {
	int a[] = { 10, 20, 30, 40, 50 };
	int* p;

	p = a;	// p 는 a[0] 을 가리킴

	printf("a[0]=%d a[1]=%d a[2]=%d \n", a[0], a[1], a[2]);
	printf("p[0]=%d p[1]=%d p[2]=%d \n\n", p[0], p[1], p[2]);	// 포인터를 배열처럼

	printf("*(a+0)=%d *(a+1)=%d *(a+2)=%d \n", *(a + 0), *(a + 1), *(a + 2));	// 배열을 포인터처럼
	printf("*(p+0)=%d *(p+1)=%d *(p+2)=%d \n", *(p + 0), *(p + 1), *(p + 2));

	return 0;
}
