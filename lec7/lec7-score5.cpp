/*

 [개념 정리 - 배열의 초기화] (시험 단골)
 - int scores[5] = { 31, 63, 62, 87, 14 };   중괄호 { } 안에 초깃값 나열
 - 초깃값이 크기보다 적으면 나머지는 0
     int a[5] = { 1, 2, 3 };  -> 1 2 3 0 0
     int a[5] = { 0 };        -> 전부 0 (자주 쓰는 패턴)
 - 크기를 생략하면 초깃값 개수만큼 크기가 정해짐
     int a[] = { 1, 2, 3 };   -> 크기 3
 - 초깃값을 안 주면 일반 변수처럼 쓰레기 값
 - 배열 크기 구하기 : sizeof(a) / sizeof(a[0])

*/

#include <stdio.h>

int main(void) {
	int scores[5] = { 31, 63, 62, 87, 14 };	// 선언과 동시에 초기화
	int i;

	for (i = 0; i < 5; i++)
		printf("scores[%d] = %d\n", i, scores[i]);

	return 0;
}
