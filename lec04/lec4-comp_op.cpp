/*

 [개념 정리 - 대입 연산자 & 복합 대입 연산자]
 - 대입 연산자 = : 오른쪽 수식의 값을 왼쪽 변수에 저장
     x = x + 1 : 수학에선 말이 안 되지만 C에선 "x 값을 1 증가"
     왼쪽에는 반드시 변수가 와야 함 (100 = x; 는 에러)
 - 대입 연산자는 연속 사용 가능 : x = y = z = 3;  (오른쪽부터 z=3 -> y=3 -> x=3)
 - 복합 대입 연산자 : 대입 + 산술 연산을 합친 것  += -= *= /= %=
     x += y  ->  x = x + y
 - 주의!! 오른쪽 전체가 먼저 계산됨 (시험 단골)
     x *= y + 1  ->  x = x * (y + 1)
     x %= x + y  ->  x = x % (x + y)

*/

#include <stdio.h>

int main(void) {
	int x = 10, y = 10;

	printf("x = %d y = %d \n", x, y);
	x += 1;	// x = x + 1
	printf("After (x += 1), x = %d \n", x);
	y *= 2;	// y = y * 2
	printf("After (y *= 2), y = %d \n", y);

	return 0;
}
