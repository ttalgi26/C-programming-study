/*

 [개념 정리 - 비트 이동 연산자]
 - << : 비트를 왼쪽으로 이동, 한 칸 이동할 때마다 값이 2배
 - >> : 비트를 오른쪽으로 이동, 한 칸 이동할 때마다 값이 1/2배 (나머지 버림)
     ex) 9 << 1 = 18   (1001 -> 10010)
         9 >> 1 = 4    (1001 -> 0100)
         15 << 2 = 60, 15 >> 2 = 3
 - x << n  ==  x * 2^n,   x >> n  ==  x / 2^n

*/

#include <stdio.h>

int main(void) {
	int x = 9;	// 1001

	printf("%d << 1 = %d\n", x, x << 1);	// 10010 = 18
	printf("%d >> 1 = %d\n", x, x >> 1);	// 0100 = 4

	return 0;
}
