/*

 [개념 정리 - 형변환(type casting)] (시험 단골)
 - 자동적인 형변환 (컴파일러가 알아서)
     올림 변환 : double f = 10;     -> f에는 10.0 저장
     내림 변환 : int i = 3.141592;  -> i에는 3 저장 (소수점 버림, 데이터 손실)
     수식에서 : 서로 다른 자료형이 섞이면 더 큰 자료형으로 통일 (int + double -> double)
 - 명시적인 형변환 : (자료형)값
     (double)5 / 4 = 5.0 / 4 = 1.25
     변수 자체의 타입이 바뀌는 게 아니라, 꺼낸 값의 타입만 바뀜
 - 주의!! 5 / 4 는 정수 나눗셈 1 -> 그 다음 double에 저장되어 1.0 (1.25 아님)
 - (int)1.3 + (int)1.8 = 1 + 1 = 2,  1.3 + 1.8 = 3.1 -> int에 저장 -> 3

*/

#include <stdio.h>

int main(void) {
	int i;
	double f;

	f = 5 / 4;	// 정수 나눗셈 1 -> 1.0 저장
	printf("(5 / 4) = %lf\n", f);

	f = (double)5 / 4;	// 5.0 / 4 -> 1.25
	printf("(double)5 / 4 = %lf\n", f);

	i = 1.3 + 1.8;	// 3.1 -> 내림 변환 -> 3
	printf("1.3 + 1.8 = %d\n", i);

	i = (int)1.3 + (int)1.8;	// 1 + 1 = 2
	printf("(int)1.3 + (int)1.8 = %d\n", i);

	return 0;
}
