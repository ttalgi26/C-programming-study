/*

 [개념 정리 - 증감 연산자 ++, --] (시험 단골!)
 - x++;  ==  x = x + 1;      x--;  ==  x = x - 1;
 - 전위(++x) : 먼저 증가시키고 그 값을 사용
 - 후위(x++) : 먼저 현재 값을 사용하고 나중에 증가
     x = 1; y = ++x;  -> x = 2, y = 2
     x = 1; y = x++;  -> x = 2, y = 1
 - 단독으로 쓸 때(x++; 또는 ++x;)는 결과가 같음, 다른 수식 안에서 쓸 때 차이 남

*/

#include <stdio.h>

int main(void) {
	int x, y;

	x = 1;	// x는 1
	y = ++x;	// 전위 : x 증가 후 대입 -> x는 2, y는 2
	printf("x=%d y=%d \n", x, y);

	y = x++;	// 후위 : 대입 후 x 증가 -> y는 2, x는 3
	printf("x=%d y=%d \n", x, y);

	return 0;
}
