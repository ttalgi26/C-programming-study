/*

 [개념 정리 - 지역 변수와 전역 변수] (시험 단골)
 - 지역 변수(local variable) : 함수나 블록 안에서 선언된 변수
     선언된 함수(블록) 안에서만 사용 가능, 다른 함수에서는 접근 불가
     함수가 호출될 때 생성, 함수가 끝나면 사라짐
     초기화하지 않으면 쓰레기 값!! (int result; result += i; -> 잘못된 결과)
     매개변수도 지역 변수의 일종
 - 전역 변수(global variable) : 함수 외부에서 선언된 변수
     모든 함수에서 사용 가능
     프로그램 시작과 동시에 생성, 프로그램 종료 시까지 존재
     초기화하지 않으면 0 으로 자동 초기화
     어디서든 변경 가능해서 어디서 바뀌었는지 추적이 어려움 -> 사용을 권장하지 않음
 - 같은 이름의 전역 변수와 지역 변수가 있으면 지역 변수가 전역 변수를 가린다

*/

#include <stdio.h>

int global = 123;	// 전역 변수 (모든 함수에서 사용 가능)
int sum = 123;	// 전역 변수
int zero;	// 초기화 안 한 전역 변수 -> 0

void sub1()
{
	printf("global=%d\n", global);	// 전역 변수 사용
}

void sub2()
{
	printf("global=%d\n", global);	// 다른 함수에서도 사용 가능
}

int main(void) {
	sub1();
	sub2();

	int sum = 321;	// 같은 이름의 지역 변수
	printf("sum=%d \n", sum);	// 지역 변수가 전역 변수를 가림 -> 321
	printf("zero=%d \n", zero);	// 전역 변수 기본값 0

	return 0;
}
