/*

 [개념 정리 - 화살표 키 입력받기]
 - 화살표 키는 _getch() 를 두 번 읽어야 함
     첫 번째 값 224 (특수 키라는 표시) -> 두 번째 값으로 방향 구분
     75 왼쪽(←)   77 오른쪽(→)   72 위(↑)   80 아래(↓)
 - 2차원 char 배열 board[y][x] 로 맵 표현 ('#' 벽, '.' 길, '@' 주인공)
     board[행][열] = board[y][x]  (x 가 가로, y 가 세로)
 - 교재 코드에 추가한 부분 : 벽('#')에 닿으면 실패, 맵 밖으로 못 나가게, 오른쪽 끝에 도착하면 성공
   (교재 문제 설명 "한 번이라도 벽에 닿으면 실패" 반영)

*/

#include <stdio.h>
#include <stdlib.h>
#include <conio.h>

int main(void) {
	char board[10][10] = { {'#', '#', '#', '#', '.', '.', '.', '.', '.', '.' },
						   {'.', '.', '.', '.', '.', '#', '.', '.', '.', '.' },
						   {'#', '#', '#', '.', '#', '.', '.', '.', '.', '.' },
						   {'.', '.', '#', '.', '.', '#', '.', '.', '.', '.' },
						   {'.', '.', '#', '.', '.', '#', '.', '.', '.', '.' },
						   {'.', '.', '#', '.', '.', '#', '.', '.', '.', '.' },
						   {'.', '.', '.', '#', '.', '.', '#', '#', '.', '.' },
						   {'.', '.', '.', '.', '#', '.', '.', '.', '#', '#' },
						   {'.', '.', '.', '.', '.', '#', '.', '.', '.', '.' },
						   {'.', '.', '.', '.', '.', '#', '#', '#', '#', '#' } };
	int xpos = 0, ypos = 1;	// 왼쪽 입구
	board[ypos][xpos] = '@';

	// 사용자로부터 위치를 받아서 보드에 표시한다.
	while (1) {
		system("cls");
		printf("Left:<-, Right:-> Up:^, Down:V\n");
		for (int y = 0; y < 10; y++) {
			for (int x = 0; x < 10; x++) printf("%c", board[y][x]);
			printf("\n");
		}
		board[ypos][xpos] = '.';	// 현재 위치 지우기

		int nx = xpos, ny = ypos;	// 이동할 위치
		int ch = _getch();
		if (ch == 224) {	// 화살표 키
			int ch2 = _getch();
			if (ch2 == 75) nx--;	// 왼쪽
			else if (ch2 == 80) ny++;	// 아래
			else if (ch2 == 72) ny--;	// 위
			else if (ch2 == 77) nx++;	// 오른쪽
		}
		if (nx < 0 || nx > 9 || ny < 0 || ny > 9) {	// 맵 밖이면 이동 안 함
			nx = xpos; ny = ypos;
		}
		if (board[ny][nx] == '#') {	// 벽에 닿음
			printf("You hit the wall. Failed.\n");
			break;
		}
		xpos = nx; ypos = ny;
		board[ypos][xpos] = '@';

		if (xpos == 9) {	// 오른쪽 출구 도착
			printf("You escaped!\n");
			break;
		}
	}

	return 0;
}
