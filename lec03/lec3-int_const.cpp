/*

 [개념 정리 - 정수형 상수 (진법 표기)]
 - 10진수 : 그냥 씀            ex) 128
 - 8진수  : 앞에 0 붙임        ex) 0200  (= 128)
 - 16진수 : 앞에 0x 붙임       ex) 0x80  (= 128)
 - 형식 지정자 : %d 10진수, %o 8진수, %x 16진수
     # 붙이면 접두사까지 출력 -> %#o : 0200,  %#x : 0x80
 - 상수 뒤 접미사 : 123L (long), 123U (unsigned), 123LL (long long)
 - 16진수는 하드웨어 제어에 많이 사용 (비트 패턴 보기 쉬움)
     ex) 8개 LED 중 첫 번째(최상위 비트) 켜기 -> 10000000 = 0x80

*/

#include <stdio.h>

int main(void) {
	printf("%d %#x %#o \n", 128, 128, 128);	// 128 0x80 0200

	int dec = 128;	// 10진수
	int oct = 0200;	// 8진수 (앞에 0)
	int hex = 0x80;	// 16진수 (앞에 0x)
	printf("dec=%d oct=%d hex=%d \n", dec, oct, hex);	// 모두 128

	return 0;
}
