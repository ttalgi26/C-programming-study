/*

 [개념 정리 - 부동소수점의 오버플로우와 언더플로우]
 - 오버플로우 : 너무 큰 수 -> 저장 범위를 넘으면 무한대(inf)가 됨
     float 최대값은 약 3.4e38 -> 1e39 는 저장 불가 -> inf
 - 언더플로우 : 너무 작은 수(0에 가까운 수) -> 표현할 수 없으면 0이 됨
 - %e : 지수 표기법으로 출력 (1.23e+05 = 1.23 x 10^5)

*/

#include <stdio.h>

int main(void) {
	float x = 1e39;	// float은 3.4e38까지만 저장 가능 -> 오버플로우
	float y = 1.23456e-46;	// 너무 작은 값 -> 언더플로우

	printf("x=%e\n", x);	// inf
	printf("y=%e\n", y);	// 0.000000e+00

	return 0;
}
