/*

 [개념 정리 - 부동소수점은 부정확할 수 있다]
 - 0.1 을 출력하면 0.10000000149011611938 처럼 정확하지 않게 나옴
 - 이유 : 이진법으로는 정확하게 나타낼 수 없는 값이 있기 때문
     10진법에서 1/3 = 0.3333... 이 끝나지 않는 것처럼
     2진법에서 0.1 = 0.000110011... 이 무한히 반복됨
 - 그래서 실수끼리 == 로 비교하는 것은 위험함
 - %.20f : 소수점 이하 20자리까지 출력

*/

#include <stdio.h>

int main(void) {
	float value = 0.1;

	printf("%.20f \n", value);	// 0.1이 정확히 출력되지 않음

	return 0;
}
